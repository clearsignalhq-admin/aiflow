class McpExporter:
    def export(self, workflow: Workflow, cases: Optional[list[dict[str, Any]]] = None, run_seed: int = 0) -> dict[str, str]:
        """Return the project as ``{relative path: file text}``. ``cases`` and ``run_seed`` are accepted for a uniform API
        (suite cases describe whole-workflow behaviour, which a tool server does not run)."""
        plan = _Plan(workflow, "mcp")
        tools = [n for n in plan.nodes if n.type in TOOL_TYPES]
        if not tools:
            raise ExportError("This workflow has no TOOL, API, DATABASE or RAG steps, so there is nothing to expose as an MCP tool.")

        definition = {
            "server": _project_slug(workflow.name),
            "tools": [self._tool(plan, n) for n in tools],
        }
        files: dict[str, str] = {
            "workflow.json": json.dumps(workflow.model_dump(mode="json"), indent=2, ensure_ascii=False) + "\n",
            "tools.json": json.dumps(definition, indent=2, ensure_ascii=False) + "\n",
            "server.py": SERVER_PY,
            "integrations.py": plan.integrations_py(),
            "runtime.py": tpl.RUNTIME_PY,
            "aiflow_expressions.py": inspect.getsource(expressions_module),
            "aiflow_schema.py": inspect.getsource(schema_module),
            "requirements.txt": self._requirements(tools),
            ".env.example": plan.env_example(),
            "pytest.ini": tpl.PYTEST_INI,
            "README.md": self._readme(workflow, definition, plan),
            "tests/test_tools.py": TEST_TOOLS_PY,
        }
        if plan.uses_connectors:
            files["connectors.py"] = connectors_module.CONNECTORS_PY
        return files

    def export_zip(self, workflow: Workflow, cases: Optional[list[dict[str, Any]]] = None, run_seed: int = 0) -> tuple[str, bytes]:
        return zip_project(f"{_project_slug(workflow.name)}-mcp", self.export(workflow, cases, run_seed))

    # ── tool definitions ────────────────────────────────────────────────────
    def _tool(self, plan: _Plan, n: WorkflowNode) -> dict[str, Any]:
        return {
            "name": plan.names[n.id],
            "description": self._description(n),
            "inputSchema": self._input_schema(n),
            "function": plan._stub_name(n),
        }

    @staticmethod
    def _description(n: WorkflowNode) -> str:
        cfg = n.config
        if n.type == NodeType.TOOL:
            text = cfg.get("description") or cfg.get("name") or n.name
        elif n.type == NodeType.API:
            effect = "changes data" if _is_irreversible(n) else "reads data"
            text = f"{n.name}: {str(cfg.get('method') or 'GET').upper()} {cfg.get('url') or ''} ({effect})"
        elif n.type == NodeType.DATABASE:
            text = f"{n.name}: runs a database query that {'writes' if _is_irreversible(n) else 'reads'} data"
        else:
            text = f"{n.name}: searches the knowledge base '{cfg.get('knowledgeBase') or ''}'"
        return _safe_text(text, 300) or n.name

    @staticmethod
    def _placeholder_fields(value: Any) -> list[str]:
        found: list[str] = []

        def visit(v: Any) -> None:
            if isinstance(v, str):
                for m in _PLACEHOLDER.finditer(v):
                    if m.group(1) != "input" and m.group(1) not in found:
                        found.append(m.group(1))
            elif isinstance(v, dict):
                for x in v.values():
                    visit(x)
            elif isinstance(v, list):
                for x in v:
                    visit(x)

        visit(value)
        return found

    def _input_schema(self, n: WorkflowNode) -> dict[str, Any]:
        """The data contract if the step declares one, else what its settings reference, else free-form."""
        declared = n.input_schema
        if isinstance(declared, dict) and isinstance(declared.get("properties"), dict) and not schema_module.check_schema(declared):
            return {**declared, "type": "object"}

        cfg = n.config
        fields: list[str] = []
        properties: dict[str, Any] = {}
        referenced = [cfg.get(k) for k in ("url", "query", "body", "headers") if k in cfg]
        if n.type == NodeType.RAG:
            referenced.append(cfg.get("query"))
        for name in self._placeholder_fields(referenced):
            fields.append(name)
            properties[name] = {}
        request_props = (cfg.get("requestSchema") or {}).get("properties") if n.type == NodeType.API else None
        if isinstance(request_props, dict):
            for name, spec in request_props.items():
                properties.setdefault(name, spec if isinstance(spec, dict) else {})
        if n.type == NodeType.RAG and not fields:
            properties["query"] = {"type": "string", "description": "What to search for"}
            fields.append("query")

        schema: dict[str, Any] = {"type": "object", "properties": properties}
        if fields:
            schema["required"] = fields
        if not properties:
            schema["additionalProperties"] = True       # nothing declared: accept whatever the caller sends
        return schema

    @staticmethod
    def _requirements(tools: list[WorkflowNode]) -> str:
        lines = ["mcp>=1.2,<2", "python-dotenv>=1.0", "pytest>=8"]
        types_used = {n.type for n in tools}
        if NodeType.API in types_used:
            lines.append("httpx>=0.27")
        if NodeType.DATABASE in types_used:
            lines += ["sqlalchemy>=2,<3", "# add the driver for your database, for example: psycopg2-binary (PostgreSQL), pymysql (MySQL)"]
        if NodeType.RAG in types_used:
            lines.append("langchain-openai>=1.0,<2   # only used for embeddings when OPENAI_API_KEY is set")
        return "\n".join(lines) + "\n"

    def _readme(self, workflow: Workflow, definition: dict[str, Any], plan: _Plan) -> str:
        rows = ["| Tool | From step | What it does |", "|---|---|---|"]
        by_name = {plan.names[n.id]: n for n in plan.nodes}
        for tool in definition["tools"]:
            node = by_name[tool["name"]]
            rows.append(f"| `{tool['name']}` | {node.type.value} “{_safe_text(node.name, 40)}” | {tool['description'].replace('|', '/')} |")
        server = definition["server"]
        config = json.dumps({"mcpServers": {server: {"command": "python", "args": ["/full/path/to/server.py"], "env": {"AIFLOW_MOCK": "1"}}}}, indent=2)
        return "\n".join([
            f"# {_safe_text(workflow.name, 80)} — MCP tools",
            "",
            "The tool steps of an AiFlow workflow, served over the Model Context Protocol so any MCP client can call them.",
            "Generated by AiFlow; `workflow.json` is the workflow as designed and each tool reads its settings from it.",
            "",
            "## Tools",
            "",
            *rows,
            "",
            "Tool names, descriptions and input schemas are in `tools.json`. A step's input schema (data contract) becomes the tool's "
            "input schema; otherwise it is derived from the `{{fields}}` the step's settings use.",
            "",
            "## Run it",
            "",
            "```bash",
            "python -m venv .venv && source .venv/bin/activate   # Windows: .venv\\Scripts\\activate",
            "pip install -r requirements.txt",
            "cp .env.example .env",
            "",
            "pytest                       # checks the definitions and runs every tool in mock mode",
            "AIFLOW_MOCK=1 python server.py   # serve over stdio with fixtures (no credentials)",
            "python server.py             # serve for real",
            "```",
            "",
            "Add it to an MCP client, for example Claude Desktop's `claude_desktop_config.json`:",
            "",
            "```json",
            config,
            "```",
            "",
            "Secrets are never in `workflow.json`: API header values and database connections written as `env:NAME` are read from "
            "the environment variable `NAME` (see `.env.example`). Set them in the client's `env` block or your shell.",
            "",
            "## Notes",
            "",
            "- API steps send real requests; DATABASE steps run the query with bound parameters; RAG steps search `knowledge/<knowledge base>/`. TOOL steps "
            "raise `NotImplementedError` until you implement them in `integrations.py`.",
            "- Only TOOL, API, DATABASE and RAG steps are exposed. Steps that call an AI model or make decisions are part of the "
            "workflow, not tools; use the LangGraph or plain Python export to run the whole workflow.",
            "- Written for the official `mcp` Python SDK, version 1.x.",
            "",
        ])
