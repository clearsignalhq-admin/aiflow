from app.services import langgraph_templates as tpl
from app.services import expressions as expressions_module
from app.services import schema_utils as schema_module
from app.services.langgraph_exporter import ExportError, _Plan, _project_slug, _safe_text, zip_project
from app.services.linter import _is_irreversible

TOOL_TYPES = (NodeType.TOOL, NodeType.API, NodeType.DATABASE, NodeType.RAG)
_PLACEHOLDER = re.compile(r"\{\{\s*([A-Za-z_][A-Za-z0-9_]*)(?:\.[A-Za-z0-9_]+)*\s*\}\}")

SERVER_PY = '''"""MCP server for the tool steps of this workflow (generated by AiFlow).

Run over stdio:   python server.py
Use mock mode:    AIFLOW_MOCK=1 python server.py      (every tool returns a fixture; no credentials needed)
"""
import asyncio
import json
from pathlib import Path

import mcp.types as types
from mcp.server import Server
from mcp.server.stdio import stdio_server

try:
    from dotenv import load_dotenv

    load_dotenv()
except ImportError:  # python-dotenv is optional
    pass

import integrations
from aiflow_schema import validate_value

DEFINITION = json.loads(Path(__file__).with_name("tools.json").read_text(encoding="utf-8"))
TOOLS = {tool["name"]: tool for tool in DEFINITION["tools"]}

server = Server(DEFINITION["server"])


@server.list_tools()
async def list_tools() -> list[types.Tool]:
    return [
        types.Tool(name=tool["name"], description=tool["description"], inputSchema=tool["inputSchema"])
        for tool in DEFINITION["tools"]
    ]


@server.call_tool()
async def call_tool(name: str, arguments: dict | None) -> list[types.TextContent]:
    tool = TOOLS.get(name)
    if tool is None:
        raise ValueError(f"Unknown tool: {name}")
    arguments = arguments or {}
    problems = validate_value(tool["inputSchema"], arguments)
    if problems:
        raise ValueError("Invalid arguments: " + "; ".join(problems[:3]))
    result = await asyncio.to_thread(getattr(integrations, tool["function"]), arguments)
    return [types.TextContent(type="text", text=json.dumps(result, default=str))]


async def main() -> None:
    async with stdio_server() as (read_stream, write_stream):
        await server.run(read_stream, write_stream, server.create_initialization_options())


if __name__ == "__main__":
    asyncio.run(main())
'''

