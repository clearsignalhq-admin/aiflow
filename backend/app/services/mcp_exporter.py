"""MCP export: the workflow's integration steps as an MCP tool server (Task 56).

TOOL, API, DATABASE and RAG steps become tools an MCP client (Claude Desktop, an IDE, an agent) can call.
The tools run the same code as the other export targets (``integrations.py`` and ``connectors.py``), with
secrets read from environment variables. Tool definitions are data (``tools.json``), never spliced into
Python, so workflow text cannot become code.

Targeted SDK: the official ``mcp`` Python package, 1.x (low-level ``Server`` API over stdio).
"""
import inspect
import json
import re
from typing import Any, Optional

from app.models.workflow import NodeType, Workflow, WorkflowNode
